#!/usr/bin/env python3
"""Convert a PSF1 console font (with unicode table) into a C array of
ASCII + Cyrillic + some symbol glyphs, 8x16 pixels each (one byte per row, MSB = leftmost pixel).

Usage: psf2c.py <font.psf[.gz]> <out.c>
The generated kernel/drivers/font8x16.c is committed to the repo, so this tool
is only needed if you want to swap the font.
"""
import gzip, sys

def load(path):
    data = open(path, 'rb').read()
    if data[:2] == b'\x1f\x8b':
        data = gzip.decompress(data)
    if data[:2] != b'\x36\x04':
        sys.exit('only PSF1 fonts are supported')
    mode, size = data[2], data[3]
    if size != 16:
        sys.exit('font must be 8x16')
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i*16: 4 + (i+1)*16] for i in range(count)]
    umap = {}
    if mode & 2:                       # unicode table: uint16 entries, 0xFFFF ends a glyph
        tbl = data[4 + count*16:]
        g = 0
        for i in range(0, len(tbl) - 1, 2):
            v = tbl[i] | tbl[i+1] << 8
            if v == 0xFFFF:
                g += 1
            elif v != 0xFFFE and v not in umap:
                umap[v] = g
    else:
        umap = {i: i for i in range(count)}
    return glyphs, umap

# Glyphs beyond ASCII: Cyrillic (for the Russian UI) and a few UI symbols.
EXTRA = [0x401, 0x451] + list(range(0x410, 0x450)) + \
        [0xB7, 0x2022, 0x2026, 0xD7, 0x2190, 0x2192, 0x2191, 0x2193, 0xB0, 0x2014, 0x2013, 0xA9, 0x2116, 0x25B6]

def main():
    glyphs, umap = load(sys.argv[1])
    extra = [cp for cp in EXTRA if cp in umap]
    out = ['/* Generated by tools/psf2c.py from %s.' % sys.argv[1].split('/')[-1],
           ' * Terminus Font (c) Dimitar Zhekov, SIL Open Font License 1.1.',
           ' * Glyphs 0-127: ASCII; 128+: the code points listed in font_extra_cp.',
           ' * 8x16, 1 byte per row, bit 7 = leftmost pixel. */',
           '#include <stdint.h>', '',
           'const int font_glyph_count = %d;' % (128 + len(extra)),
           'const uint16_t font_extra_cp[%d] = {%s};' % (len(extra), ', '.join('0x%x' % c for c in extra)), '',
           'const uint8_t font8x16[%d][16] = {' % (128 + len(extra))]
    for c in list(range(128)) + extra:
        g = glyphs[umap[c]] if ((32 <= c < 127 or c >= 128) and c in umap) else bytes(16)
        name = repr(chr(c)) if 32 <= c < 127 else ('U+%04X' % c if c >= 128 else '   ')
        out.append('    /* %s */ {%s},' % (name, ', '.join('0x%02x' % b for b in g)))
    out.append('};')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
